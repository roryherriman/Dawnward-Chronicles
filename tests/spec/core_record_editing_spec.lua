-- L1: editing narrative records in the player's words (#17, #19, #27).
local Loader = require("support.loader")

return function(t, expect)
	local function setup()
		local ns = Loader.Core()
		return ns, ns.Schema.NewCharacter(1)
	end

	t:describe("record editing", function()
		t:it("edits an arc's title, summary and kind; the arc becomes the player's", function()
			local ns, char = setup()
			local arc = ns.Arcs.Add(char, { title = "A thread of mercy", kind = "growth" }, "suggested", 1)
			local edited = ns.Arcs.Edit(char, arc.id, { title = "Learning mercy", summary = "Since Northshire",
				kind = "conviction" }, 2)
			expect.equal(edited.title, "Learning mercy")
			expect.equal(edited.summary, "Since Northshire")
			expect.equal(edited.kind, "conviction")
			expect.equal(edited.provenance, "player")
			expect.equal(edited.status, "proposed", "editing does not accept it")
			expect.falsy(ns.Arcs.Edit(char, arc.id, { title = "  " }, 3))
			expect.falsy(ns.Arcs.Edit(char, arc.id, { kind = "nonsense" }, 3))
			expect.equal(arc.title, "Learning mercy", "a refused edit changes nothing")
		end)

		t:it("edits a goal and sets or removes its level objective", function()
			local ns, char = setup()
			local g = ns.Goals.Add(char, { title = "Reach the capital" }, 1)
			ns.Goals.Edit(char, g.id, { target = 20, text = "To see the king" }, 2)
			expect.equal(g.objective.target, 20)
			expect.equal(g.text, "To see the king")
			expect.falsy(ns.Goals.Edit(char, g.id, { target = 101 }, 3))
			expect.falsy(ns.Goals.Edit(char, g.id, { target = 2.5 }, 3))
			expect.equal(g.objective.target, 20)
			ns.Goals.Edit(char, g.id, { target = false }, 4)
			expect.falsy(g.objective)
			expect.equal(g.state, "active", "never achieved by editing")
		end)

		t:it("edits a stance but never leaves it with neither side", function()
			local ns, char = setup()
			local s = ns.Identity.Add(char, { subject = "Stormwind", persona = "Loyal", conviction = "Doubts" }, 1)
			expect.falsy(ns.Identity.Edit(char, s.id, { persona = "", conviction = "" }, 2))
			expect.equal(s.persona, "Loyal")
			ns.Identity.Edit(char, s.id, { conviction = "", deliberate = true }, 3)
			expect.falsy(s.conviction)
			expect.truthy(s.deliberate)
			expect.equal(s.convictionVisibility, "private")
		end)

		t:it("renames a person but refuses a duplicate, and players keep a realm", function()
			local ns, char = setup()
			local a = ns.People.Add(char, { name = "Aria", kind = "player", realm = "Silverhand" }, 1)
			local b = ns.People.Add(char, { name = "Brom", kind = "npc" }, 1)
			expect.falsy(ns.People.Edit(char, b.id, { name = "aria", kind = "player", realm = "silverhand" }, 2))
			expect.equal(b.name, "Brom")
			expect.falsy(ns.People.Edit(char, a.id, { realm = "" }, 2))
			expect.equal(a.realm, "Silverhand")
			ns.People.Edit(char, a.id, { kind = "npc" }, 3)
			expect.falsy(a.realm, "only players carry a realm")
			ns.People.Edit(char, b.id, { relation = "Old friend" }, 4)
			expect.equal(b.relation, "Old friend")
		end)

		t:it("links a visited place as the homeland, privately, and only one at a time", function()
			local ns, char = setup()
			local P = ns.Places
			char.story.places[P.Key("Elwynn Forest", "Northshire Valley")] = P.CleanEntry({ zone = "Elwynn Forest",
				subzone = "Northshire Valley", first = 1, last = 1 })
			char.story.places[P.Key("Elwynn Forest", "Goldshire")] = P.CleanEntry({ zone = "Elwynn Forest",
				subzone = "Goldshire", first = 2, last = 2 })
			P.SetHomeland(char, P.FindByName(char, "Northshire Valley"), 5)
			expect.equal(char.fields.homeland.value, "Northshire Valley")
			expect.equal(char.fields.homeland.visibility, "private")
			char.fields.homeland.visibility = "public"
			P.SetHomeland(char, P.FindByName(char, "Goldshire"), 6)
			expect.equal(char.fields.homeland.value, "Goldshire")
			expect.equal(char.fields.homeland.visibility, "public", "the player's visibility choice is kept")
			expect.equal(P.Homeland(char).subzone, "Goldshire")
			expect.falsy(P.FindByName(char, "Northshire Valley").homeland)
			-- The link survives a save and load.
			local clean = P.CleanAll(char.story.places)
			expect.truthy(clean[P.Key("Elwynn Forest", "Goldshire")].homeland)
		end)
	end)
end
