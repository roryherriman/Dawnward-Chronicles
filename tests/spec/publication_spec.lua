-- L1 (v0.9): the publication model. New characters set up with the v0.9
-- wizard start their profile details Public; older characters keep
-- everything Private until the one-time transition, which never publishes
-- Secret items or anything outside the chosen categories.
local Loader = require("support.loader")
local Boot = require("support.boot")

return function(t, expect)
	local function legacy(ns)
		local char = ns.Schema.NewCharacter(1)
		ns.Character.SetField(char, "name", "Lirael", 2)
		ns.Character.SetField(char, "faith", "The Light", 2)
		ns.Character.SetFieldVisibility(char, "faith", "secret", 2)
		ns.Character.AddItem(char, "family", { relation = "Brother", name = "Aldric" }, 3)
		ns.Facts.Add(char, { category = "origin", statement = "Born in Lordaeron" }, nil, 4)
		ns.Personality.Set(char, "courage", 15, 5)
		ns.Sources.Capture(char, "paste", "My story.", nil, 6)
		ns.Journal.AddNote(char, { text = "A private diary entry" }, 7)
		return char
	end

	t:describe("publication model: defaults", function()
		t:it("keeps everything Private for a character without the profile model", function()
			local ns = Loader.Core()
			local char = legacy(ns)
			expect.equal(char.fields.name.visibility, "private")
			expect.equal(char.family[1].visibility, "private")
			expect.equal(char.facts[1].visibility, "private")
			expect.equal(char.personality.courage.visibility, "private")
			expect.equal(ns.Sources.Visibility(char), "private")
		end)

		t:it("starts profile details Public under the profile model, but never the journal", function()
			local ns = Loader.Core()
			local char = ns.Schema.NewCharacter(1)
			ns.Publication.Adopt(char, 1)
			ns.Character.SetField(char, "name", "Lirael", 2)
			ns.Character.AddItem(char, "family", { relation = "Brother", name = "Aldric" }, 3)
			ns.Character.AddItem(char, "history", { when = "Year 20", text = "Lordaeron fell" }, 3)
			ns.Facts.Add(char, { category = "origin", statement = "Born in Lordaeron" }, nil, 4)
			ns.Personality.Set(char, "courage", 15, 5)
			ns.Sources.Capture(char, "paste", "My story.", nil, 6)
			local entry = ns.Journal.AddNote(char, { text = "A private diary entry" }, 7)
			local stance = ns.Identity.Add(char, { subject = "The Light", persona = "Devout",
				conviction = "Doubts it" }, 8)
			expect.equal(char.fields.name.visibility, "public")
			expect.equal(char.family[1].visibility, "public")
			expect.equal(char.history[1].visibility, "public")
			expect.equal(char.facts[1].visibility, "public")
			expect.equal(char.personality.courage.visibility, "public")
			expect.equal(ns.Sources.Visibility(char), "public")
			expect.equal(entry.visibility, "private", "the journal stays private")
			expect.equal(stance.visibility, "public", "the persona is what others see")
			expect.equal(stance.convictionVisibility, "private", "a private conviction stays private")
		end)

		t:it("keeps an explicit choice, and a changed field keeps its visibility", function()
			local ns = Loader.Core()
			local char = ns.Schema.NewCharacter(1)
			ns.Publication.Adopt(char, 1)
			ns.Facts.Add(char, { category = "fear", statement = "Deep water", visibility = "secret" })
			expect.equal(char.facts[1].visibility, "secret")
			ns.Character.SetField(char, "age", "30", 2)
			ns.Character.SetFieldVisibility(char, "age", "private", 3)
			ns.Character.SetField(char, "age", "31", 4)
			expect.equal(char.fields.age.visibility, "private")
		end)

		t:it("saves and reloads the model; unknown values fall back to the original model", function()
			local ns = Loader.Core()
			local char = ns.Schema.NewCharacter(1)
			ns.Publication.Adopt(char, 9)
			local clean = ns.Schema.NormalizeCharacter(ns.Util.DeepCopy(char))
			expect.deepEqual(clean.publication, { mode = "profile", since = 9 })
			expect.deepEqual(ns.Schema.NormalizeCharacter({ publication = { mode = "everything" } }).publication, {})
			expect.deepEqual(ns.Schema.NormalizeCharacter({}).publication, {})
			local bio = ns.Schema.NormalizeCharacter({ sources = { versions = { { id = 1, kind = "paste",
				text = "x" } }, current = 1, visibility = "loud" } })
			expect.equal(ns.Sources.Visibility(bio), "private", "an unknown biography visibility is Private")
		end)
	end)

	t:describe("publication model: the one-time transition", function()
		t:it("previews counts per category and changes nothing", function()
			local ns = Loader.Core()
			local char = legacy(ns)
			local before = ns.Util.DeepCopy(char)
			local preview = ns.Publication.Preview(char)
			expect.deepEqual(preview.fields, { public = 0, private = 1, secret = 1 })
			expect.deepEqual(preview.biography, { public = 0, private = 1, secret = 0 })
			expect.deepEqual(preview.family, { public = 0, private = 1, secret = 0 })
			local lines = ns.Publication.PreviewLines(char, { fields = true })
			expect.truthy(lines[1]:find("1 Private become Public; 1 Secret stay Secret", 1, true), lines[1])
			expect.deepEqual(char, before)
		end)

		t:it("makes only the chosen Private items Public, never Secret ones or the journal", function()
			local ns = Loader.Core()
			local char = legacy(ns)
			local changed = ns.Publication.Transition(char, { fields = true, biography = true }, 50)
			expect.equal(changed.fields, 1)
			expect.equal(changed.biography, 1)
			expect.equal(changed.family, 0)
			expect.equal(char.fields.name.visibility, "public")
			expect.equal(char.fields.faith.visibility, "secret", "Secret is never published")
			expect.equal(char.family[1].visibility, "private", "not chosen: unchanged")
			expect.equal(char.facts[1].visibility, "private")
			expect.equal(char.journal[1].visibility, "private")
			expect.equal(ns.Sources.Visibility(char), "public")
			expect.deepEqual(char.publication, { mode = "profile", since = 50, transitionedAt = 50 })
			-- New items now start Public.
			ns.Facts.Add(char, { category = "belief", statement = "Protect the weak" })
			expect.equal(char.facts[2].visibility, "public")
		end)

		t:it("runs once, and refuses an unknown category without changing anything", function()
			local ns = Loader.Core()
			local char = legacy(ns)
			local before = ns.Util.DeepCopy(char)
			local ok, err = ns.Publication.Transition(char, { journal = true }, 50)
			expect.falsy(ok)
			expect.truthy(err:find("unknown category", 1, true))
			expect.deepEqual(char, before)
			expect.truthy(ns.Publication.Transition(char, {}, 60))
			expect.falsy(ns.Publication.Transition(char, { fields = true }, 70), "only once")
			expect.equal(char.fields.name.visibility, "private", "an empty choice published nothing")
		end)
	end)

	t:describe("publication model: what reaches the public projection", function()
		t:it("includes the biography text only while the biography itself is Public", function()
			local ns = Loader.Core()
			local char = legacy(ns)
			expect.falsy(ns.Projection.GetPublic(char).biography)
			ns.Sources.SetVisibility(char, "public", 9)
			local public = ns.Projection.GetPublic(char)
			expect.equal(public.biography.text, "My story.")
			expect.falsy(public.biography.kind, "where it came from is not included")
			ns.Sources.SetVisibility(char, "secret", 10)
			expect.falsy(ns.Projection.GetPublic(char).biography)
		end)
	end)

	t:describe("publication model: /dawnward publish (L2)", function()
		t:it("previews without changing anything, then switches with confirm", function()
			local mock, env, ns = Boot.Start()
			mock.Slash("set name Lirael")
			mock.Slash("set faith The Light")
			mock.Slash("vis faith secret")
			local before = ns.Util.DeepCopy(env.DawnwardChroniclesDB.characters["Testchar-TestRealm"])
			local reply = mock.Slash("publish fields")
			expect.truthy(reply:find("Nothing changes until you confirm", 1, true))
			expect.truthy(reply:find("Profile details: 1 Private become Public; 1 Secret stay Secret", 1, true), reply)
			expect.deepEqual(env.DawnwardChroniclesDB.characters["Testchar-TestRealm"], before)
			reply = mock.Slash("publish fields confirm")
			expect.truthy(reply:find("profile model", 1, true), reply)
			local char = env.DawnwardChroniclesDB.characters["Testchar-TestRealm"]
			expect.equal(char.fields.name.visibility, "public")
			expect.equal(char.fields.faith.visibility, "secret")
			expect.equal(char.publication.mode, "profile")
			expect.truthy(mock.Slash("publish all confirm"):find("already uses the profile model", 1, true))
		end)

		t:it("refuses an unknown category", function()
			local mock, env = Boot.Start()
			mock.Slash("set name Lirael")
			expect.truthy(mock.Slash("publish journal confirm"):find("Unknown category 'journal'", 1, true))
			expect.equal(env.DawnwardChroniclesDB.characters["Testchar-TestRealm"].fields.name.visibility, "private")
		end)
	end)
end
