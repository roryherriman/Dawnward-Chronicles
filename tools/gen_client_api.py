"""Generate the strict client API tables for the mock client (tests/support/wow_mock.lua)
from Blizzard's generated API documentation (Blizzard_APIDocumentationGenerated in a
checkout of github.com/Gethe/wow-ui-source).

  python tools/gen_client_api.py <wow-ui-source, branch classic_era>
      writes tests/support/client_api.lua: the methods the Classic Era client
      documents for region objects (Texture, MaskTexture, Line, FontString).

  python tools/gen_client_api.py --forever <wow-ui-source, branch forever>
      writes tests/support/client_api_forever.lua: the same region methods for
      WoW Forever (1.60.1, game type camelot), plus what the Forever mock may
      expose: the documented global functions (_globals), the functions of the
      namespaces Dawnward uses (_namespaces) and every documented event
      (_events).

The mock makes region objects strict (a method the client does not document
reads as nil, as in game), and in Forever mode builds its globals only from
these lists, so code that relies on a Classic-only API fails in the tests.
"""
import pathlib
import re
import sys

BASES = {
    "Texture": ["SimpleTextureAPI", "SimpleTextureBaseAPI"],
    "MaskTexture": ["SimpleMaskTextureAPI", "SimpleTextureBaseAPI"],
    "Line": ["SimpleLineAPI", "SimpleTextureBaseAPI"],
    "FontString": ["SimpleFontStringAPI"],
}
COMMON = ["SimpleRegionAPI", "SimpleScriptRegionAPI", "SimpleScriptRegionResizingAPI", "SimpleObjectAPI",
          "SimpleAnimatableObjectAPI", "SimpleFrameScriptObjectAPI"]
# Namespaces whose functions the Forever mock may expose (Dawnward reads these).
NAMESPACES = ["C_AddOns", "C_Map", "C_QuestLog", "C_Reputation", "C_Timer"]
FUNC = re.compile(r'Name = "(\w+)",\s*\n\s*Type = "Function"')
EVENT = re.compile(r'LiteralName = "(\w+)"')


def functions(doc_dir, name):
    path = doc_dir / (name + "Documentation.lua")
    if not path.exists():
        return set()
    return set(FUNC.findall(path.read_text(encoding="utf-8")))


def regions(doc_dir, out):
    common = set()
    for name in COMMON:
        common |= functions(doc_dir, name)
    for kind, names in sorted(BASES.items()):
        methods = set(common)
        for name in names:
            methods |= functions(doc_dir, name)
        out.append("\t%s = {" % kind)
        for m in sorted(methods):
            out.append("\t\t%s = true," % m)
        out.append("\t},")


def systems(doc_dir):
    """Documented global functions, namespace functions and events."""
    globals_, spaces, events = set(), {}, set()
    for path in sorted(doc_dir.glob("*.lua")):
        text = path.read_text(encoding="utf-8")
        events |= set(EVENT.findall(text))
        kind = re.search(r'Type = "(\w+)"', text)
        if kind and kind.group(1) == "ScriptObject":
            continue
        space = re.search(r'Namespace = "(\w+)"', text)
        if space:
            spaces.setdefault(space.group(1), set()).update(FUNC.findall(text))
        else:
            globals_ |= set(FUNC.findall(text))
    return globals_, spaces, events


def names(out, key, values):
    out.append("\t%s = {" % key)
    for v in sorted(values):
        out.append("\t\t%s = true," % v)
    out.append("\t},")


def main():
    args = sys.argv[1:]
    forever = "--forever" in args
    args = [a for a in args if a != "--forever"]
    root = pathlib.Path(args[0])
    doc_dir = root / "Interface" / "AddOns" / "Blizzard_APIDocumentationGenerated"
    support = pathlib.Path(__file__).resolve().parent.parent / "tests" / "support"
    if not forever:
        out = ["-- Generated by tools/gen_client_api.py from Blizzard_APIDocumentationGenerated",
               "-- (wow-ui-source, classic_era). Do not edit by hand.",
               "return {"]
        regions(doc_dir, out)
        out.append("}")
        target = support / "client_api.lua"
    else:
        globals_, spaces, events = systems(doc_dir)
        out = ["-- Generated by tools/gen_client_api.py --forever from Blizzard_APIDocumentationGenerated",
               "-- (wow-ui-source, branch forever: WoW Forever 1.60.1 (70755), game type camelot).",
               "-- Do not edit by hand.",
               "return {"]
        regions(doc_dir, out)
        names(out, "_globals", globals_)
        out.append("\t_namespaces = {")
        for space in NAMESPACES:
            out.append("\t\t%s = {" % space)
            for fn in sorted(spaces.get(space, set())):
                out.append("\t\t\t%s = true," % fn)
            out.append("\t\t},")
        out.append("\t},")
        names(out, "_events", events)
        out.append("}")
        target = support / "client_api_forever.lua"
    target.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote", target)


if __name__ == "__main__":
    main()
