"""Generate tests/support/client_api.lua: the methods the WoW Classic Era
client documents for region objects (Texture, MaskTexture, Line, FontString),
from Blizzard's generated API documentation (Blizzard_APIDocumentationGenerated
in a checkout of github.com/Gethe/wow-ui-source, branch classic_era).

The mock client (tests/support/wow_mock.lua) uses it to make those objects
strict: a method the client does not document reads as nil, as in game.

Usage: python tools/gen_client_api.py <path to wow-ui-source>
"""
import pathlib
import re
import sys

BASES = {
    "Texture": ["SimpleTextureAPI", "SimpleTextureBaseAPI"],
    "MaskTexture": ["SimpleMaskTextureAPI", "SimpleTextureBaseAPI"],
    "Line": ["SimpleLineAPI", "SimpleTextureBaseAPI"],
    "FontString": ["SimpleFontStringAPI"],
}
COMMON = ["SimpleRegionAPI", "SimpleScriptRegionAPI", "SimpleScriptRegionResizingAPI", "SimpleObjectAPI",
          "SimpleAnimatableObjectAPI", "SimpleFrameScriptObjectAPI"]
FUNC = re.compile(r'Name = "(\w+)",\s*\n\s*Type = "Function"')


def functions(doc_dir, name):
    path = doc_dir / (name + "Documentation.lua")
    if not path.exists():
        return set()
    return set(FUNC.findall(path.read_text(encoding="utf-8")))


def main():
    root = pathlib.Path(sys.argv[1])
    doc_dir = root / "Interface" / "AddOns" / "Blizzard_APIDocumentationGenerated"
    common = set()
    for name in COMMON:
        common |= functions(doc_dir, name)
    out = ["-- Generated by tools/gen_client_api.py from Blizzard_APIDocumentationGenerated",
           "-- (wow-ui-source, classic_era). Do not edit by hand.",
           "return {"]
    for kind, names in sorted(BASES.items()):
        methods = set(common)
        for name in names:
            methods |= functions(doc_dir, name)
        out.append("\t%s = {" % kind)
        for m in sorted(methods):
            out.append("\t\t%s = true," % m)
        out.append("\t},")
    out.append("}")
    target = pathlib.Path(__file__).resolve().parent.parent / "tests" / "support" / "client_api.lua"
    target.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote", target, {k: None for k in BASES})


if __name__ == "__main__":
    main()
